#!/usr/bin/env bash
# [2026-10-15] | INFO | SCRIPTS.INSTALL_SH | One-command end-user installer for
# Llama Nexus (Linux / macOS / WSL2). Detects hardware, writes .env, pulls
# prebuilt images from GHCR, starts the stack, and prints next steps.
#
# Usage:  curl -fsSL <repo>/install.sh | bash    (or: bash install.sh)
# Options (env vars):
#   INSTALL_DIR   target directory (default: ./llama-nexus)
#   HF_TOKEN      HuggingFace token (optional; only for gated models)
#   API_KEY       inference API key (default: randomly generated)
#   SKIP_START=1  prepare only, don't start containers

set -euo pipefail

BLUE='\033[0;34m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; RED='\033[0;31m'; NC='\033[0m'
info()  { echo -e "${BLUE}[info]${NC} $*"; }
ok()    { echo -e "${GREEN}[ok]${NC} $*"; }
warn()  { echo -e "${YELLOW}[warn]${NC} $*"; }
die()   { echo -e "${RED}[error]${NC} $*" >&2; exit 1; }

INSTALL_DIR="${INSTALL_DIR:-./llama-nexus}"

echo "=============================================="
echo "  Llama Nexus — local AI stack installer"
echo "=============================================="

# --- Preflight -------------------------------------------------------------
command -v docker >/dev/null 2>&1 || die "Docker is not installed. Install Docker Engine or Docker Desktop: https://docs.docker.com/get-docker/"
docker info >/dev/null 2>&1 || die "Docker daemon is not reachable. Start Docker and re-run."
if ! docker compose version >/dev/null 2>&1; then
  die "Docker Compose v2 is required (plugin ships with modern Docker). Update Docker."
fi
ok "Docker + Compose v2 available"

# --- Platform / GPU tier detection -----------------------------------------
OS="$(uname -s)"
GPU_TIER="cpu"
LLAMACPP_IMAGE="ghcr.io/aleckarfonta/llama-nexus-llamacpp:cpu"
COMPOSE_FILES=(-f docker-compose.yml -f docker-compose.prebuilt.yml)

if command -v nvidia-smi >/dev/null 2>&1 && nvidia-smi >/dev/null 2>&1; then
  CAP="$(nvidia-smi --query-gpu=compute_cap --format=csv,noheader 2>/dev/null | head -1 | tr -d ' ')"
  VRAM_MB="$(nvidia-smi --query-gpu=memory.total --format=csv,noheader,nounits 2>/dev/null | sort -n | tail -1)"
  # nvidia-container-toolkit check (GPU usable inside containers)
  if docker info 2>/dev/null | grep -qi nvidia; then
    case "$CAP" in
      12.*) GPU_TIER="cuda-120";;
      8.9)  GPU_TIER="cuda-89";;
      8.6)  GPU_TIER="cuda-86";;
      *)    GPU_TIER="cuda-86"; warn "Unrecognized compute cap '$CAP' — defaulting to cuda-86 image";;
    esac
    LLAMACPP_IMAGE="ghcr.io/aleckarfonta/llama-nexus-llamacpp:${GPU_TIER}"
    COMPOSE_FILES+=(-f docker-compose.gpu.yml)
    ok "NVIDIA GPU detected (compute ${CAP}, ${VRAM_MB}MB) — tier: ${GPU_TIER}"
  else
    warn "NVIDIA GPU present but nvidia-container-toolkit not configured; installing CPU tier."
    warn "For GPU acceleration: https://docs.nvidia.com/datacenter/cloud-native/container-toolkit/install-guide.html"
  fi
else
  ok "No NVIDIA GPU detected — installing CPU tier (small models only)"
fi

if [[ "$OS" == "Darwin" ]]; then
  warn "macOS: Docker runs in a Linux VM without GPU passthrough. CPU tier only;"
  warn "pick small models (Qwen3-4B Q4 or smaller) for usable speed."
fi

# --- Download / enter repo --------------------------------------------------
if [[ ! -f "$INSTALL_DIR/docker-compose.yml" ]]; then
  info "Cloning Llama Nexus into ${INSTALL_DIR}..."
  git clone --depth 1 https://github.com/alecKarfonta/llama-nexus.git "$INSTALL_DIR"
fi
cd "$INSTALL_DIR"

# --- .env generation --------------------------------------------------------
if [[ -f .env ]]; then
  warn ".env already exists — leaving it in place"
else
  GEN_API_KEY="${API_KEY:-$(head -c 24 /dev/urandom | base64 | tr -dc 'a-zA-Z0-9' | head -c 32)}"
  cat > .env <<EOF
# [2026-10-15] | INFO | INSTALL.ENV | Generated by install.sh — edit freely.
# Inference API key (used by llamacpp/vllm/ninfer and the web UI proxy).
API_KEY=${GEN_API_KEY}
# Optional: HuggingFace token for gated models (leave empty otherwise).
HUGGINGFACE_TOKEN=${HF_TOKEN:-}
# Prebuilt llamacpp image tier selected by installer (${GPU_TIER}).
LLAMACPP_DOCKER_IMAGE=${LLAMACPP_IMAGE}
EOF
  ok ".env written (API key generated)"
fi

# --- Pull + start -----------------------------------------------------------
if [[ "${SKIP_START:-0}" == "1" ]]; then
  ok "Prepared. Start manually with:"
  echo "  cd $INSTALL_DIR"
  echo "  docker compose ${COMPOSE_FILES[*]} up -d"
  exit 0
fi

info "Pulling prebuilt images (a few minutes; no compilation)..."
docker compose "${COMPOSE_FILES[@]}" pull backend-api llamacpp-frontend

info "Starting stack..."
docker compose "${COMPOSE_FILES[@]}" up -d

# --- Report -----------------------------------------------------------------
HOST_IP="localhost"
cat <<EOF

${GREEN}Llama Nexus is starting.${NC}
  Web UI:      http://${HOST_IP}:3002
  Backend API: http://${HOST_IP}:8700
  LLM API:     http://${HOST_IP}:8600/v1  (OpenAI-compatible)

Next steps:
  1. Open http://${HOST_IP}:3002 — the first-run wizard helps you pick and
     download a model matched to your hardware.
  2. Wait for model download, then click Deploy.
  3. Start chatting. Voice (STT/TTS) and RAG services can be enabled from the UI.

Logs:    docker compose ${COMPOSE_FILES[*]} logs -f
Stop:    docker compose ${COMPOSE_FILES[*]} down
EOF
