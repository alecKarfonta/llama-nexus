# [2026-10-15] | INFO | SCRIPTS.INSTALL_PS1 | One-command end-user installer for
# Llama Nexus on Windows (native Docker Desktop or WSL2). Detects hardware,
# writes .env, pulls prebuilt GHCR images, starts the stack.
#
# Usage (PowerShell as Administrator recommended for WSL2 check):
#   irm <repo>/install.ps1 | iex        (or: powershell -ExecutionPolicy Bypass -File install.ps1)
# Options (env vars):
#   $env:INSTALL_DIR  target directory (default: .\llama-nexus)
#   $env:HF_TOKEN     HuggingFace token (optional)
#   $env:SKIP_START   "1" = prepare only

$ErrorActionPreference = "Stop"

function Info($msg) { Write-Host "[info] $msg" -ForegroundColor Blue }
function Ok($msg)   { Write-Host "[ok] $msg" -ForegroundColor Green }
function Warn($msg) { Write-Host "[warn] $msg" -ForegroundColor Yellow }
function Die($msg)  { Write-Host "[error] $msg" -ForegroundColor Red; exit 1 }

Write-Host "==============================================" 
Write-Host "  Llama Nexus - local AI stack installer (Win)" 
Write-Host "==============================================" 

$InstallDir = if ($env:INSTALL_DIR) { $env:INSTALL_DIR } else { ".\llama-nexus" }

# --- Preflight ---------------------------------------------------------------
try { docker version | Out-Null } catch {
    Die "Docker is not installed/running. Install Docker Desktop (WSL2 backend): https://docs.docker.com/desktop/install/windows-install/"
}
Ok "Docker available"

if ($env:OS -ne "Windows_NT") { Die "Run this script in PowerShell on Windows" }

# WSL2 hint (Docker Desktop uses WSL2 backend by default)
$wsl = $false
try { wsl --status 2>$null | Out-Null; if ($LASTEXITCODE -eq 0) { $wsl = $true } } catch {}
if ($wsl) { Ok "WSL2 detected (Docker Desktop backend)" }
else { Warn "WSL2 not detected - Docker Desktop Hyper-V mode may be slower" }

# --- GPU tier detection --------------------------------------------------------
$GpuTier = "cpu"
$LlamacppImage = "ghcr.io/aleckarfonta/llama-nexus-llamacpp:cpu"
$ComposeFiles = @("-f", "docker-compose.yml", "-f", "docker-compose.prebuilt.yml")

# nvidia-smi on Windows host
$nvidia = Get-Command nvidia-smi -ErrorAction SilentlyContinue
if ($nvidia) {
    try {
        $cap = (& nvidia-smi --query-gpu=compute_cap --format=csv,noheader 2>$null | Select-Object -First 1).Trim()
        $dockerInfo = docker info 2>$null | Out-String
        if ($dockerInfo -match "nvidia" -or $wsl) {
            # WSL2 + Docker Desktop: nvidia-container-toolkit is built in when GPU driver is present
            switch ($cap) {
                "12.0" { $GpuTier = "cuda-120" }
                "8.9"  { $GpuTier = "cuda-89" }
                default { $GpuTier = "cuda-86" }
            }
            $LlamacppImage = "ghcr.io/aleckarfonta/llama-nexus-llamacpp:$GpuTier"
            $ComposeFiles += @("-f", "docker-compose.gpu.yml")
            Ok "NVIDIA GPU detected (compute $cap) - tier: $GpuTier"
        } else {
            Warn "NVIDIA GPU present but Docker GPU runtime not detected; installing CPU tier"
        }
    } catch {
        Warn "nvidia-smi query failed; installing CPU tier"
    }
} else {
    Ok "No NVIDIA GPU detected - CPU tier (small models only)"
}

# --- Clone repo ----------------------------------------------------------------
if (-not (Test-Path "$InstallDir/docker-compose.yml")) {
    Info "Cloning Llama Nexus into $InstallDir..."
    git clone --depth 1 https://github.com/alecKarfonta/llama-nexus.git $InstallDir
    if ($LASTEXITCODE -ne 0) { Die "git clone failed. Install git: https://git-scm.com/download/windows" }
}
Set-Location $InstallDir

# --- .env generation -------------------------------------------------------------
if (Test-Path .env) {
    Warn ".env already exists - leaving it in place"
} else {
    $GenKey = if ($env:API_KEY) { $env:API_KEY } else {
        -join ((48..57) + (65..90) + (97..122) | Get-Random -Count 32 | ForEach-Object { [char]$_ })
    }
    $HfToken = if ($env:HF_TOKEN) { $env:HF_TOKEN } else { "" }
    @"
# [2026-10-15] | INFO | INSTALL.ENV | Generated by install.ps1 - edit freely.
API_KEY=$GenKey
HUGGINGFACE_TOKEN=$HfToken
LLAMACPP_DOCKER_IMAGE=$LlamacppImage
"@ | Out-File -FilePath .env -Encoding ascii
    Ok ".env written (API key generated)"
}

# --- Pull + start ----------------------------------------------------------------
if ($env:SKIP_START -eq "1") {
    Ok "Prepared. Start manually with:"
    Write-Host "  cd $InstallDir"
    Write-Host "  docker compose $($ComposeFiles -join ' ') up -d"
    exit 0
}

Info "Pulling prebuilt images (a few minutes; no compilation)..."
& docker compose @ComposeFiles pull backend-api llamacpp-frontend
if ($LASTEXITCODE -ne 0) { Die "docker compose pull failed" }

Info "Starting stack..."
& docker compose @ComposeFiles up -d
if ($LASTEXITCODE -ne 0) { Die "docker compose up failed" }

Write-Host @"

Llama Nexus is starting.
  Web UI:      http://localhost:3002
  Backend API: http://localhost:8700
  LLM API:     http://localhost:8600/v1  (OpenAI-compatible)

Next steps:
  1. Open http://localhost:3002 - the first-run wizard helps you pick and
     download a model matched to your hardware.
  2. Wait for the model download, then click Deploy.
  3. Start chatting. Voice (STT/TTS) and RAG services can be enabled from the UI.

Logs:    docker compose $($ComposeFiles -join ' ') logs -f
Stop:    docker compose $($ComposeFiles -join ' ') down
"@ -ForegroundColor Green
